export function renderIcon(iconName, customClass = '') {
  const svg = ICONS[iconName];
  if (!svg) return document.createTextNode('');
  const wrapper = h('span', { className: `icon-wrapper ${customClass}`.trim(), innerHTML: svg });
  return wrapper;
}
